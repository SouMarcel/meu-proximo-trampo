/**
 * Vagas de exemplo, só para o modo demonstração (servidor fora do ar na abertura). Empresas e pessoas
 * fictícias, no formato do servidor (types/api.ts). Com o servidor no ar, nada daqui aparece.
 */
function diasAtras(n: number): string {
  const d = new Date()
  d.setDate(d.getDate() - n)
  const p = (x: number) => String(x).padStart(2, "0")
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`
}

